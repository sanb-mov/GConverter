const DICTIONARIES: Record<LanguageCode, Dict> = { en, es }

export type TranslateParams = Record<string, string | number>

/**
 * Translate `key` into `lang`, substituting `{placeholders}`.
 *
 * Unknown keys are returned verbatim, which lets free-form text (custom
 * preset names, ffprobe codec names) pass through the same call site.
 */
export function t(lang: LanguageCode, key: string, params?: TranslateParams): string {
  const template = DICTIONARIES[lang]?.[key] ?? en[key] ?? key
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    params[name] !== undefined ? String(params[name]) : match
  )
}

/** Bind a language once and reuse it — the common case in components. */
export function translator(lang: LanguageCode): (key: string, params?: TranslateParams) => string {
  return (key, params) => t(lang, key, params)
}

/** Every key defined in English, used by the coverage test. */
export function englishKeys(): string[] {
  return Object.keys(en)
}

export function dictionaryFor(lang: LanguageCode): Dict {
  return DICTIONARIES[lang]
}
