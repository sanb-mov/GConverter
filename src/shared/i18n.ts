/**
 * Internationalisation.
 *
 * The dictionary lives in `shared` because user-facing text is produced on
 * both sides of the IPC boundary: the renderer draws the interface, while
 * the main process generates conversion verdicts, warnings and error
 * explanations. Both call the same `t()`.
 *
 * `t()` falls back to English for a missing translation, and to the key
 * itself when the key is unknown — so free-form text (a custom preset name,
 * for example) can be passed through unchanged.
 */

